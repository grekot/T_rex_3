"""Pixel art postaci Pupila: siatki 24 x 24, dinozaury patrzą w prawo.

Znaki:
  .  przezroczyste        O  obrys
  B  ciało                L  jasny brzuch
  D  ciemniejsze plamy    A  akcent (kolce, rogi, grzebień)
  W  białe (zęby, pazury)
  e  oko (pole 2 x 2, rysowane według miny)
  m  usta (zwykle kreska obrysu, otwarte = czerwone)
  c  policzek (różowy, gdy się cieszy albo je)
"""

FORMS = {}


def form(fid, palette, rows, legs=3):
    rows = [r for r in rows.strip("\n").split("\n")]
    rows = [r.split(" ", 1)[1] if r[:2].isdigit() else r for r in rows]
    assert len(rows) == 24, (fid, len(rows))
    for i, r in enumerate(rows):
        assert len(r) == 24, (fid, i, len(r), r)
    FORMS[fid] = {"palette": palette, "rows": rows, "legs": legs}


def pal(body, light, dark, accent):
    return {"B": body, "L": light, "D": dark, "A": accent}


